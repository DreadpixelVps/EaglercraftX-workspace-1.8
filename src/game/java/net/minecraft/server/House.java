    private void setblock(World world, BlockPos origin, String command) {
        try {
            String[] parts = command.split("\\s+");
            if (parts.length >= 5) {
                int x = Integer.parseInt(parts[1].replace("~", ""));
                int y = Integer.parseInt(parts[2].replace("~", ""));
                int z = Integer.parseInt(parts[3].replace("~", ""));
                String blockName = parts[4];

                BlockPos pos = origin.add(x, y, z);
                
                Block block = Block.getBlockFromName(blockName);
                if (block != null) {
                    world.setBlockState(pos, block.getDefaultState(), 2);
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
